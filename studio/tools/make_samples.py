"""Rebuilds js/samples.js from the sample frames in assets/.

The studio inlines its two sample creatives as data URIs so that pixel analysis
works even when index.html is opened straight from disk (file:// images would
taint the canvas).

    python3 studio/tools/make_samples.py
"""
import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SAMPLES = {
    "usual": "sample-usual-ad.jpg",
    "halfsecond": "sample-halfsecond.jpg",
}

out = {}
for key, name in SAMPLES.items():
    with open(os.path.join(ROOT, "assets", name), "rb") as f:
        out[key] = "data:image/jpeg;base64," + base64.b64encode(f.read()).decode("ascii")

with open(os.path.join(ROOT, "js", "samples.js"), "w") as f:
    f.write("// Generated by tools/make_samples.py. Frames from Reel 01, 540x960.\n")
    f.write("const SAMPLES = " + json.dumps(out) + ";\n")
print("wrote js/samples.js")
